function ProfileBadge({ profile, showLabel = true, size = 'small' }) {
  const meta = ProfileMeta[profile];
  if (!meta) return null;

  const IconComponent = ProfileIcons[meta.icon];
  const iconSize = size === 'small' ? 10 : 12;

  return (
    <span
      className={`profile-badge profile-badge--${size}`}
      style={{ '--badge-color': meta.color }}
      title={`${meta.label} connection`}
    >
      {IconComponent && <IconComponent size={iconSize} />}
      {showLabel && <span className="profile-badge__label">{meta.label}</span>}
    </span>
  );
}

export default ProfileBadge;
